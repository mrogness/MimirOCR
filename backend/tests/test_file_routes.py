@pytest.fixture
def file_api(tmp_path, monkeypatch):
    app = FastAPI()
    app.include_router(file_routes.router)
    engine = create_engine(
        "sqlite://", connect_args={"check_same_thread": False}, poolclass=StaticPool
    )
    sessions = sessionmaker(bind=engine)
    Base.metadata.create_all(engine)

    def override_get_db():
        with sessions() as db:
            yield db

    app.dependency_overrides[get_db] = override_get_db
    store = JobStore()
    monkeypatch.setattr(file_routes, "job_store", store)
    roots = {}
    for accessor, name in (
        ("get_output_dir", "output"),
        ("get_temp_dir", "temporary"),
        ("get_uploads_dir", "uploads"),
    ):
        path = tmp_path / name
        path.mkdir()
        roots[name] = path
        monkeypatch.setattr(file_routes, accessor, lambda path=path: path)

    try:
        # Observe HTTP 500 responses while inspecting persisted state after faults.
        with TestClient(app, raise_server_exceptions=False) as client:
            yield SimpleNamespace(client=client, sessions=sessions, store=store, **roots)
    finally:
        app.dependency_overrides.clear()
        engine.dispose()


