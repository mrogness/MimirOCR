def test_successful_replacement_clears_only_target_dataset(existing_projects, pdf_bytes):
    existing = existing_projects
    api = existing.api
    other_before = project_snapshot(existing, 10)
    old_upload, old_job = existing.records[1]
    response = upload_pdf(api, 1, pdf_bytes)
    assert response.status_code == 200, response.text
    payload = response.json()
    assert payload["upload_id"] != old_upload.upload_id
    record = api.store.get_upload(payload["upload_id"])
    assert record is not None
    with api.sessions() as db:
        project = db.get(Project, 1)
        assert project.source_pdf_name == "new.pdf"
        assert project.source_pdf_path == record.stored_path
        assert project.ocr_last_status is None
        assert project.ocr_last_elapsed_seconds is None
        assert project.ocr_run_count == 3
        assert db.get(Page, 100) is None
        assert db.get(Line, 1000) is None
    assert Path(record.stored_path).read_bytes() == pdf_bytes
    assert api.store.get_upload(old_upload.upload_id) is None
    assert api.store.get_job(old_job.job_id) is None
    assert api.store.list_project_jobs(1) == []
    for path in existing.artifacts[1]:
        assert not path.exists(), f"Previous artifact was retained: {path}"
    assert project_snapshot(existing, 10) == other_before


def test_repeated_uploads_use_unique_ids_and_paths(file_api, pdf_bytes):
    with file_api.sessions() as db:
        db.add(Project(id=1, name="Test"))
        db.commit()
    first = upload_pdf(file_api, 1, pdf_bytes, filename="same.pdf")
    assert first.status_code == 200
    first_id = first.json()["upload_id"]
    first_record = file_api.store.get_upload(first_id)
    first_path = Path(first_record.stored_path)
    second = upload_pdf(file_api, 1, pdf_bytes, filename="same.pdf")
    assert second.status_code == 200
    second_id = second.json()["upload_id"]
    second_record = file_api.store.get_upload(second_id)
    assert second_id != first_id
    assert second_record.stored_path != str(first_path)
    assert file_api.store.get_upload(first_id) is None
    assert not first_path.exists()
    assert Path(second_record.stored_path).read_bytes() == pdf_bytes


