def test_dpi_analysis_returns_analyzer_result_without_replacing_data(existing_projects, monkeypatch, pdf_bytes):
    existing = existing_projects
    before = project_snapshot(existing, 1)
    calls = []

    def analyze(data, filename):
        calls.append((data, filename))
        return PdfDpiAnalysisResponse(
            filename=filename, page_count=2, pages_analyzed=2,
            pages_with_scan_estimate=2, detected_median_dpi=400,
            detected_min_dpi=350, detected_max_dpi=450, recommended_dpi=400,
            confidence="high", ignored_probable_watermark_images=1,
            warnings=["Example analyzer warning"],
        )

    monkeypatch.setattr(file_routes, "analyze_pdf_dpi", analyze)
    response = existing.api.client.post(
        "/files/analyze-pdf-dpi", files={"file": ("../../scan.pdf", pdf_bytes, "application/pdf")}
    )
    assert response.status_code == 200, response.text
    assert calls == [(pdf_bytes, "scan.pdf")]
    assert response.json() == {
        "filename": "scan.pdf", "page_count": 2, "pages_analyzed": 2,
        "pages_with_scan_estimate": 2, "detected_median_dpi": 400,
        "detected_min_dpi": 350, "detected_max_dpi": 450,
        "recommended_dpi": 400, "confidence": "high",
        "ignored_probable_watermark_images": 1,
        "warnings": ["Example analyzer warning"],
    }
    assert project_snapshot(existing, 1) == before
    assert len(list(existing.api.uploads.iterdir())) == 2


