def project_snapshot(existing, project_id):
    """Check meaningful saved data, source files, and retained upload/job records."""
    api = existing.api
    with api.sessions() as db:
        project = db.get(Project, project_id)
        pages = db.query(Page).filter(Page.project_id == project_id).order_by(Page.id).all()
        lines = db.query(Line).join(Page).filter(Page.project_id == project_id).order_by(Line.id).all()
        upload, job = existing.records[project_id]
        return {
            "project": (project.name, project.source_pdf_name, project.source_pdf_path,
                        project.ocr_run_count, project.ocr_last_status, project.ocr_last_elapsed_seconds),
            "pages": [(page.id, page.page_number, page.img_path) for page in pages],
            "lines": [(line.id, line.page_id, line.ocr_text, line.corrected_text, line.img_path) for line in lines],
            "artifacts": [(str(path), path.read_bytes() if path.is_file() else None)
                          for path in existing.artifacts[project_id]],
            "upload_retained": api.store.get_upload(upload.upload_id) is not None,
            "job_retained": api.store.get_job(job.job_id) is not None,
        }


def upload_pdf(api, project_id, pdf_bytes, filename="new.pdf", content_type="application/pdf"):
    return api.client.post(
        f"/files/projects/{project_id}/upload-pdf",
        files={"file": (filename, pdf_bytes, content_type)},
    )


def test_upload_stores_bytes_and_project_metadata(file_api, pdf_bytes):
    api = file_api
    with api.sessions() as db:
        db.add(Project(id=1, name="New project"))
        db.commit()
    response = upload_pdf(api, 1, pdf_bytes, filename="Æble.pdf")
    assert response.status_code == 200, response.text
    payload = response.json()
    assert payload["project_id"] == 1
    assert payload["filename"] == "Æble.pdf"
    assert payload["message"] == "Uploaded"
    record = api.store.get_upload(payload["upload_id"])
    assert record is not None
    assert record.project_id == 1
    assert record.filename == "Æble.pdf"
    stored = Path(record.stored_path)
    assert stored.parent == api.uploads
    assert stored.name.startswith("1_")
    assert stored.read_bytes() == pdf_bytes
    with api.sessions() as db:
        project = db.get(Project, 1)
        assert project.source_pdf_name == "Æble.pdf"
        assert project.source_pdf_path == str(stored)
    assert api.store.list_project_jobs(1) == []  # Upload itself does not start OCR.


