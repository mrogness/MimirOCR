"""File API contracts, replacement isolation, and upload failure regressions.

Run through pytest so backend/tests/conftest.py isolates import-time paths.
Uploads use real SQLite, a real isolated JobStore, temporary files, and a PDF
generated by ReportLab. DPI route tests replace only the PDF analyzer boundary;
they do not measure the analyzer's accuracy or require PyMuPDF/ML dependencies.

Failure regressions protect prior data and remove partially written replacements
when uploads cannot be read or saved. No failure is skipped or marked xfail.
"""

