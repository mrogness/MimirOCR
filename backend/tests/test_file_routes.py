def test_upload_read_failure_preserves_previous_dataset(existing_projects, pdf_bytes, monkeypatch):
    existing = existing_projects
    before = project_snapshot(existing, 1)
    other_before = project_snapshot(existing, 10)

    async def fail_read(self, size=-1):
        raise OSError("Simulated upload read failure")

    monkeypatch.setattr(UploadFile, "read", fail_read)
    response = upload_pdf(existing.api, 1, pdf_bytes)
    assert response.status_code == 500
    assert project_snapshot(existing, 10) == other_before
    assert project_snapshot(existing, 1) == before, "Read failure destroyed the previous project dataset"
    assert len(list(existing.api.uploads.iterdir())) == 2


def test_upload_write_failure_preserves_previous_dataset(existing_projects, pdf_bytes, monkeypatch):
    existing = existing_projects
    before = project_snapshot(existing, 1)
    other_before = project_snapshot(existing, 10)
    original_write_bytes = Path.write_bytes

    def fail_new_upload_write(path, data):
        if path.parent == existing.api.uploads:
            raise OSError("Simulated disk full")
        return original_write_bytes(path, data)

    monkeypatch.setattr(Path, "write_bytes", fail_new_upload_write)
    response = upload_pdf(existing.api, 1, pdf_bytes)
    assert response.status_code == 500
    assert project_snapshot(existing, 10) == other_before
    assert project_snapshot(existing, 1) == before, "Write failure destroyed the previous project dataset"
    assert len(list(existing.api.uploads.iterdir())) == 2


